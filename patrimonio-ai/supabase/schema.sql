-- Catálogo e histórico para um projeto Supabase novo.
-- Se já houver tabelas com estes nomes, confira as colunas e o vínculo
-- entre espécies e grupos antes de aplicar.
begin;

create table if not exists public.grupos_patrimonio (
  id bigint generated by default as identity primary key,
  nome text not null unique check (btrim(nome) <> '')
);

create table if not exists public.especies_patrimonio (
  id bigint generated by default as identity primary key,
  grupo_id bigint not null references public.grupos_patrimonio (id),
  nome text not null check (btrim(nome) <> ''),
  vida_util_anos numeric check (vida_util_anos > 0),
  valor_residual_percentual numeric check (valor_residual_percentual between 0 and 100),
  unique (grupo_id, nome)
);

create table if not exists public.consultas_patrimonio (
  id bigint generated by default as identity primary key,
  termo_pesquisado text not null,
  grupo_sugerido text not null,
  especie_sugerida text not null,
  vida_util_sugerida numeric,
  valor_residual_sugerido numeric,
  criado_em timestamptz not null default now()
);

alter table public.grupos_patrimonio enable row level security;
alter table public.especies_patrimonio enable row level security;
alter table public.consultas_patrimonio enable row level security;

revoke all on public.grupos_patrimonio, public.especies_patrimonio, public.consultas_patrimonio
  from anon, authenticated;

grant select on public.grupos_patrimonio, public.especies_patrimonio to service_role;
grant insert on public.consultas_patrimonio to service_role;

commit;
